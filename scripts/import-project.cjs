'use strict';
const fs = require('node:fs');
const path = require('node:path');
const { randomUUID } = require('node:crypto');
function importProject(filename, projectRoot = path.resolve(__dirname, '..')) {
  const data = JSON.parse(fs.readFileSync(path.resolve(filename), 'utf8'));
  const project = data.project;
  if (data.format !== 'original-prototype-editor' || data.version !== 1 || !project || !Array.isArray(project.pages) || !project.pages.length) throw Error('Use a JSON file generated by File > Save project');
  for (const field of ['theme', 'topNav']) if (typeof project[field] !== 'string') throw Error('Missing ' + field);
  for (const field of ['content', 'typeStyles', 'shellByType']) if (!project[field] || typeof project[field] !== 'object' || Array.isArray(project[field])) throw Error('Missing ' + field);
  const safeKey = key => typeof key === 'string' && /^[a-zA-Z0-9][a-zA-Z0-9_-]*$/.test(key) && !['constructor', 'prototype'].includes(key);
  const keys = new Set(), urls = new Set();
  for (const page of project.pages) {
    if (!safeKey(page.key) || keys.has(page.key) || typeof page.url !== 'string' || urls.has(page.url) || !Array.isArray(page.path) || typeof project.content[page.key] !== 'string') throw Error('Invalid or duplicated page: ' + page.key);
    keys.add(page.key); urls.add(page.url);
    if (['config', 'maintenance'].includes(page.type) && typeof project.shellByType[page.type] !== 'string') throw Error('Missing page shell: ' + page.type);
  }
  for (const field of ['content', 'typeStyles', 'shellByType']) for (const [key, value] of Object.entries(project[field])) if (!safeKey(key) || typeof value !== 'string') throw Error('Invalid resource: ' + field + '/' + key);
  const root = path.resolve(projectRoot);
  const target = path.join(root, 'src/prototype'), id = Date.now() + '-' + randomUUID().slice(0, 8);
  const stage = path.join(root, '.qa/import-' + id), backup = path.join(root, '.qa/backups/prototype-' + id);
  for (const file of [target, stage, backup]) if (!path.resolve(file).startsWith(root + path.sep)) throw Error('Output path escaped the project');
  const source = structuredClone(project);
  source.editorStartKey = keys.has(data.currentPage) ? data.currentPage : (keys.has(source.editorStartKey) ? source.editorStartKey : source.pages[0].key);
  const definition = { project: Object.fromEntries(Object.entries(source).filter(([key]) => !['theme', 'typeStyles', 'topNav', 'shellByType', 'content'].includes(key))), order: Object.keys(source), files: { theme: 'styles/theme.css', typeStyles: {}, topNav: 'top-nav.html', shellByType: {}, content: {} } };
  function write(file, text) { const destination = path.join(stage, file); fs.mkdirSync(path.dirname(destination), { recursive: true }); fs.writeFileSync(destination, text); }
  write('styles/theme.css', source.theme); write('top-nav.html', source.topNav);
  for (const [field, folder, extension] of [['content', 'pages', 'html'], ['typeStyles', 'styles/types', 'css'], ['shellByType', 'shells', 'html']]) {
    for (const [key, value] of Object.entries(source[field])) { const file = folder + '/' + key + '.' + extension; definition.files[field][key] = file; write(file, value); }
  }
  write('project.json', JSON.stringify(definition, null, 2) + '\n');
  fs.mkdirSync(path.dirname(target), { recursive: true });
  let backedUp = false;
  if (fs.existsSync(target)) { fs.mkdirSync(path.dirname(backup), { recursive: true }); fs.cpSync(target, backup, { recursive: true }); backedUp = true; }
  // Copy resources first and commit the manifest last. Avoid renaming whole
  // directories: Windows folder policies and open editors can reject that.
  function copyResources(from, to, relative = '') {
    fs.mkdirSync(to, { recursive: true });
    for (const entry of fs.readdirSync(from, { withFileTypes: true })) {
      const next = path.join(relative, entry.name);
      if (next === 'project.json') continue;
      if (entry.isDirectory()) copyResources(path.join(from, entry.name), path.join(to, entry.name), next);
      else fs.copyFileSync(path.join(from, entry.name), path.join(to, entry.name));
    }
  }
  try { copyResources(stage, target); fs.copyFileSync(path.join(stage, 'project.json'), path.join(target, 'project.json')); }
  catch (error) { if (backedUp) fs.cpSync(backup, target, { recursive: true }); throw error; }
  return { pages: source.pages.length, source: target, backup: backedUp ? backup : null };
}
module.exports = { importProject };
if (require.main === module) {
  try { if (process.argv.length !== 3) throw Error('Usage: npm run import-project -- ./my-project.json'); console.log(JSON.stringify(importProject(process.argv[2]), null, 2)); console.log('Imported source data. Run npm run build or npm start next.'); }
  catch (error) { console.error(error.message); process.exitCode = 1; }
}
